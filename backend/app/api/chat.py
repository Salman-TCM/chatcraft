router = APIRouter(prefix="/api/chat", tags=["chat"])

_optional_bearer = HTTPBearer(auto_error=False)

# Monthly message cap per role
_ROLE_CAPS: dict[UserRole, int] = {
    UserRole.free: settings.free_tier_message_cap,
    UserRole.trial: settings.trial_tier_message_cap,
    UserRole.premium: settings.premium_tier_message_cap,
}
# creator and admin have no cap


# ── Streaming chat ────────────────────────────────────────────────────────────

@router.post("/{chatbot_id}")
async def stream_chat(
    chatbot_id: uuid.UUID,
    body: ChatRequest,
    request: Request,
    background_tasks: BackgroundTasks,
    db: DBSession,
    redis: RedisClient,
    authorization: HTTPAuthorizationCredentials | None = _optional_bearer,
    x_guest_id: str | None = Header(default=None),
) -> StreamingResponse:
    # ── resolve identity ──────────────────────────────────────────────────────
    user: User | None = None
    guest_id: str | None = None

    if authorization:
        try:
            payload = decode_token(authorization.credentials)
            if payload.get("type") == "access":
                user = await db.get(User, payload.get("sub", ""))
        except JWTError:
            pass

    if not user:
        guest_id = x_guest_id or str(uuid.uuid4())

    # ── load chatbot ──────────────────────────────────────────────────────────
    bot = await db.get(ChatbotConfig, chatbot_id)
    if not bot or not bot.published:
        # Owners can still chat with unpublished bots if authenticated
        if not bot or (user is None or bot.user_id != user.id):
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail={"success": False, "error": "Chatbot not found", "code": "NOT_FOUND"},
            )

    # ── message cap check ─────────────────────────────────────────────────────
    if user:
        role = user.role
        if role in _ROLE_CAPS:
            count = await _count_user_messages_this_month(db, user.id)
            cap = _ROLE_CAPS[role]
            if count >= cap:
                raise HTTPException(
                    status_code=status.HTTP_429_TOO_MANY_REQUESTS,
                    detail={
                        "success": False,
                        "error": "Monthly message limit reached",
                        "code": "MESSAGE_CAP_REACHED",
                        "cap": cap,
                    },
                )
    else:
        # guest cap check via Redis
        count = await _guest_message_count(redis, guest_id)  # type: ignore[arg-type]
        if count >= settings.free_tier_message_cap:
            raise HTTPException(
                status_code=status.HTTP_429_TOO_MANY_REQUESTS,
                detail={
                    "success": False,
                    "error": "Monthly message limit reached",
                    "code": "MESSAGE_CAP_REACHED",
                    "cap": settings.free_tier_message_cap,
                },
            )

    # ── resolve/create conversation ───────────────────────────────────────────
    conv: Conversation | None = None
    if body.conversation_id:
        conv = await db.get(Conversation, body.conversation_id)
        if conv and conv.chatbot_id != chatbot_id:
            conv = None  # safety — don't allow cross-chatbot injection

    if not conv:
        conv = Conversation(
            chatbot_id=chatbot_id,
            user_id=user.id if user else None,
            guest_id=guest_id,
        )
        db.add(conv)
        await db.flush()  # get conv.id without committing

    is_first_message = await _is_first_message(db, conv.id)

    # ── persist user message ──────────────────────────────────────────────────
    sanitized = sanitize(body.message)
    user_msg = Message(
        conversation_id=conv.id,
        role=MessageRole.user,
        content=sanitized,
    )
    db.add(user_msg)
    await db.commit()
    await db.refresh(conv)

    # ── increment guest cap in Redis ──────────────────────────────────────────
    if guest_id:
        await _increment_guest_count(redis, guest_id)

    # ── build LLM message history ─────────────────────────────────────────────
    model_id = bot.default_model
    if body.model and bot.allow_model_switch:
        model_id = body.model

    llm_router = LLMRouter(
        model=model_id,
        fallback_model=bot.fallback_model or settings.default_fallback_model,
    )

    sys_ctx = SystemPromptContext(
        chatbot_name=bot.name,
        custom_instructions=bot.system_prompt,
    )
    system_prompt = build_system_prompt(sys_ctx)

    history = await _load_history_for_context(db, conv.id, limit=20)
    llm_messages: list[ChatMessage] = [ChatMessage(role="system", content=system_prompt)]
    llm_messages.extend(history)

    # ── stream response ───────────────────────────────────────────────────────
    conv_id = conv.id

    async def event_generator() -> AsyncIterator[str]:
        full_content: list[str] = []

        try:
            async for chunk in llm_router.stream(llm_messages):
                if await request.is_disconnected():
                    break

                if chunk.done:
                    # Persist assistant message
                    assistant_msg = Message(
                        conversation_id=conv_id,
                        role=MessageRole.assistant,
                        content="".join(full_content),
                        model=chunk.model,
                        input_tokens=chunk.input_tokens,
                        output_tokens=chunk.output_tokens,
                        cost_usd=chunk.cost_usd,
                    )
                    async with _new_session() as session:
                        session.add(assistant_msg)
                        await session.commit()
                        await session.refresh(assistant_msg)
                        msg_id = assistant_msg.id

                    yield _sse(
                        type="done",
                        model=chunk.model,
                        input_tokens=chunk.input_tokens,
                        output_tokens=chunk.output_tokens,
                        cost_usd=str(chunk.cost_usd),
                        conversation_id=str(conv_id),
                        message_id=str(msg_id),
                    )

                    # Auto-generate title after first turn (background)
                    if is_first_message:
                        background_tasks.add_task(
                            _generate_title,
                            conv_id,
                            body.message,
                            "".join(full_content),
                            model_id,
                        )
                else:
                    full_content.append(chunk.delta)
                    yield _sse(type="delta", content=chunk.delta)

        except Exception as exc:
            yield _sse(type="error", error=str(exc))

    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "X-Accel-Buffering": "no",
            "X-Guest-ID": guest_id or "",
        },
    )


# ── Conversation history ──────────────────────────────────────────────────────

@router.get("/{chatbot_id}/history", response_model=dict)
async def get_history(
    chatbot_id: uuid.UUID,
    db: DBSession,
    page: int = 1,
    per_page: int = 20,
    authorization: HTTPAuthorizationCredentials | None = _optional_bearer,
) -> dict:
    user = await _resolve_user(authorization, db)
    if not user:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED,
                            detail={"success": False, "error": "Authentication required",
                                    "code": "NOT_AUTHENTICATED"})

    offset = (page - 1) * per_page
    total_result = await db.execute(
        select(func.count()).select_from(Conversation).where(
            Conversation.chatbot_id == chatbot_id,
            Conversation.user_id == user.id,
        )
    )
    total = total_result.scalar_one()

    result = await db.execute(
        select(Conversation)
        .where(Conversation.chatbot_id == chatbot_id, Conversation.user_id == user.id)
        .options(selectinload(Conversation.messages))
        .order_by(Conversation.updated_at.desc())
        .offset(offset)
        .limit(per_page)
    )
    convs = result.scalars().all()

    return {
        "success": True,
        "data": [ConversationResponse.model_validate(c) for c in convs],
        "total": total,
        "page": page,
        "per_page": per_page,
    }


# ── Delete conversation ───────────────────────────────────────────────────────

@router.delete("/conversations/{conversation_id}", response_model=dict)
async def delete_conversation(
    conversation_id: uuid.UUID,
    db: DBSession,
    authorization: HTTPAuthorizationCredentials | None = _optional_bearer,
) -> dict:
    user = await _resolve_user(authorization, db)
    if not user:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED,
                            detail={"success": False, "error": "Authentication required",
                                    "code": "NOT_AUTHENTICATED"})

    conv = await db.get(Conversation, conversation_id)
    if not conv or conv.user_id != user.id:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND,
                            detail={"success": False, "error": "Conversation not found",
                                    "code": "NOT_FOUND"})

    await db.delete(conv)
    await db.commit()
    return {"success": True, "data": None}


# ── Message feedback ──────────────────────────────────────────────────────────

@router.post("/messages/{message_id}/feedback", response_model=dict)
async def set_feedback(
    message_id: uuid.UUID,
    body: FeedbackRequest,
    db: DBSession,
    authorization: HTTPAuthorizationCredentials | None = _optional_bearer,
) -> dict:
    user = await _resolve_user(authorization, db)
    if not user:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED,
                            detail={"success": False, "error": "Authentication required",
                                    "code": "NOT_AUTHENTICATED"})

    msg = await db.get(Message, message_id)
    if not msg:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND,
                            detail={"success": False, "error": "Message not found",
                                    "code": "NOT_FOUND"})

    # Verify ownership via conversation
    conv = await db.get(Conversation, msg.conversation_id)
    if not conv or conv.user_id != user.id:
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN,
                            detail={"success": False, "error": "Forbidden", "code": "FORBIDDEN"})

    msg.feedback = body.feedback
    await db.commit()
    return {"success": True, "data": MessageResponse.model_validate(msg)}


# ── Helpers ───────────────────────────────────────────────────────────────────

def _sse(**kwargs) -> str:
    return f"data: {json.dumps(kwargs)}\n\n"


async def _resolve_user(
    credentials: HTTPAuthorizationCredentials | None,
    db: AsyncSession,
) -> User | None:
    if not credentials:
        return None
    try:
        payload = decode_token(credentials.credentials)
        if payload.get("type") != "access":
            return None
        return await db.get(User, payload.get("sub", ""))
    except JWTError:
        return None


async def _count_user_messages_this_month(
    db: AsyncSession, user_id: uuid.UUID
) -> int:
    now = datetime.now(timezone.utc)
    start = now.replace(day=1, hour=0, minute=0, second=0, microsecond=0)
    result = await db.execute(
        select(func.count())
        .select_from(Message)
        .join(Conversation, Message.conversation_id == Conversation.id)
        .where(
            Conversation.user_id == user_id,
            Message.role == MessageRole.user,
            Message.created_at >= start,
        )
    )
    return result.scalar_one()


async def _guest_message_count(redis: aioredis.Redis, guest_id: str) -> int:
    now = datetime.now(timezone.utc)
    key = f"guest_cap:{guest_id}:{now.year}-{now.month:02d}"
    val = await redis.get(key)
    return int(val) if val else 0


async def _increment_guest_count(redis: aioredis.Redis, guest_id: str) -> None:
    now = datetime.now(timezone.utc)
    key = f"guest_cap:{guest_id}:{now.year}-{now.month:02d}"
    _, days_in_month = monthrange(now.year, now.month)
    # TTL covers the rest of the month plus a one-day buffer
    remaining_seconds = (days_in_month - now.day + 2) * 86400
    pipe = redis.pipeline()
    pipe.incr(key)
    pipe.expire(key, remaining_seconds)
    await pipe.execute()


async def _is_first_message(db: AsyncSession, conversation_id: uuid.UUID) -> bool:
    result = await db.execute(
        select(func.count()).select_from(Message).where(
            Message.conversation_id == conversation_id,
            Message.role == MessageRole.user,
        )
    )
    # Will be 1 after the message we just inserted
    return result.scalar_one() <= 1


async def _load_history_for_context(
    db: AsyncSession, conversation_id: uuid.UUID, limit: int = 20
) -> list[ChatMessage]:
    """Return the last `limit` non-system messages as LLM ChatMessage objects."""
    result = await db.execute(
        select(Message)
        .where(
            Message.conversation_id == conversation_id,
            Message.role != MessageRole.system,
        )
        .order_by(Message.created_at.desc())
        .limit(limit)
    )
    msgs = list(reversed(result.scalars().all()))
    return [ChatMessage(role=m.role.value, content=m.content) for m in msgs]


def _new_session():
    """Return a new AsyncSession context manager for background persistence."""
    from app.db.session import AsyncSessionLocal
    return AsyncSessionLocal()


async def _generate_title(
    conversation_id: uuid.UUID,
    user_message: str,
    assistant_reply: str,
    model: str,
) -> None:
    """Generate a short conversation title and persist it."""
    try:
        from app.db.session import AsyncSessionLocal

        prompt = [
            ChatMessage(
                role="system",
                content=(
                    "Generate a short, descriptive title (max 8 words, no quotes) "
                    "for a conversation that started with the following exchange."
                ),
            ),
            ChatMessage(role="user", content=f"User: {user_message[:500]}\nAssistant: {assistant_reply[:500]}"),
        ]
        router = LLMRouter(model=model)
        response = await router.complete(prompt, max_tokens=20, temperature=0.3)
        title = response.content.strip().strip('"').strip("'")[:500]

        async with AsyncSessionLocal() as session:
            conv = await session.get(Conversation, conversation_id)
            if conv and not conv.title:
                conv.title = title
                await session.commit()
    except Exception:
        pass  # Title generation is best-effort; never crash the chat flow
