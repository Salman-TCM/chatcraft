"""
Chat API — streaming SSE chat, conversation history, and message feedback.

Auth model:
  - Authenticated users: Bearer token in Authorization header.
  - Guests: no token; X-Guest-ID header used as identity (generated by frontend).

Message cap enforcement:
  - Per-role monthly limits checked before each assistant turn.
  - Guests are capped at the free-tier limit.
  - Cap breach returns 429 with code MESSAGE_CAP_REACHED.
"""
